use crate::error::AppResult;
use crate::render::PdfRenderer;
use crate::transport::windows_spooler::WindowsSpooler;
use serde::Deserialize;
use std::path::PathBuf;
use std::time::Instant;
use tauri::{AppHandle, Manager};

#[derive(Debug, Deserialize)]
pub struct PrintRequest {
    pub printer_name: String,
    pub html: String,
    pub page_width_mm: Option<f64>,
    pub page_height_mm: Option<f64>,
    pub orientation: Option<String>,
    pub copies: Option<u32>,
}

#[derive(Debug, serde::Serialize)]
pub struct PrintResponse {
    pub success: bool,
    pub job_id: String,
    pub duration_ms: u128,
    pub error: Option<String>,
}

/// Spike command: print HTML to a system printer silently
#[tauri::command]
pub async fn print_html(
    app: AppHandle,
    req: PrintRequest,
) -> AppResult<PrintResponse> {
    let start = Instant::now();
    let job_id = uuid::Uuid::new_v4().to_string();

    // Get cache directory for PDF rendering
    let cache_dir = app.path().app_cache_dir()?;
    std::fs::create_dir_all(&cache_dir)?;

    // Step 1: Render HTML to PDF
    let renderer = PdfRenderer::new(cache_dir);
    let pdf_bytes = renderer
        .html_to_pdf(
            &req.html,
            req.page_width_mm.unwrap_or(210.0),
            req.page_height_mm.unwrap_or(297.0),
            req.orientation.as_deref().unwrap_or("portrait"),
        )
        .await
        .map_err(|e| crate::error::AppError::Internal(e.to_string()))?;

    // Step 2: Send to printer via Windows spooler
    #[cfg(windows)]
    let result = {
        let spooler = WindowsSpooler::new(req.printer_name.clone());
        spooler.send_raw(&pdf_bytes)
    };
    #[cfg(not(windows))]
    let result: Result<(), String> = Ok(());

    let duration = start.elapsed().as_millis();

    match result {
        Ok(_) => Ok(PrintResponse {
            success: true,
            job_id,
            duration_ms: duration,
            error: None,
        }),
        Err(e) => Ok(PrintResponse {
            success: false,
            job_id,
            duration_ms: duration,
            error: Some(e),
        }),
    }
}

/// Enumerate system printers
#[tauri::command]
pub fn enumerate_system_printers() -> AppResult<Vec<crate::transport::PrinterInfo>> {
    #[cfg(windows)]
    {
        Ok(WindowsSpooler::enumerate_printers())
    }
    #[cfg(not(windows))]
    {
        Ok(vec![])
    }
}

/// Spike command: print a hard-coded test page
#[tauri::command]
pub async fn spike_test_print(app: AppHandle) -> AppResult<PrintResponse> {
    let test_html = r#"
<!DOCTYPE html>
<html>
<head><title>PrintNinja Test</title></head>
<body>
    <h1>PrintNinja Spike Test</h1>
    <p>If you can read this, the silent print pipeline works!</p>
    <p>Page size: A4 (210mm x 297mm)</p>
    <hr>
    <p><small>Generated by PrintNinja</small></p>
</body>
</html>
"#;

    let req = PrintRequest {
        printer_name: "Microsoft Print to PDF".to_string(),
        html: test_html.to_string(),
        page_width_mm: Some(210.0),
        page_height_mm: Some(297.0),
        orientation: Some("portrait".to_string()),
        copies: Some(1),
    };

    print_html(app, req).await
}
